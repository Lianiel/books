                  關的言說」，內容包括「中國的佛教思想」，因佛教在唐朝之後佔中國宗教之首；「中國的民間小說」，特別以《西遊記》及《紅樓夢》為例來說明「罪與懺悔」；還有「史家文人的筆鋒」、「久遠深廣的見證」、「哲學寓言成語故事」等，藉這些史實與見證，可使人更明白「罪」與華人的關係。第五章探討「現代華人與『罪』的關係」，分別從兩種處境來看現代華人，一從文化處境，也就是華人的性格與傳統文化相關的部分；二從社會處境，也就是華人的行為與今日社會相關的部分。這兩方面的探討，能使我們明瞭，現代華人仍存在著與過去華人相同的個人的罪及社會性的罪。第六章探討「從『罪』得釋放──華人文化更新之路」，先說明「中國文化與基督教思想的關係」，而後從這關係的三個角度，以浪子回頭、天人合一、內聖外王為主題再進深的探討。說明中國古聖先賢的理想靠人自己難以實現，因為罪是攔阻；但在基督裡則能實現，因為祂為人贖罪，並且創造了新人類。
